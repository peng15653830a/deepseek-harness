import { readFile, rename, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const sourceRoot = path.join(root, 'src/client')
const templatePath = path.join(sourceRoot, 'main.js')
const outputPath = path.join(root, 'lib/client.js')
const banner = '// Generated by pnpm build:client; do not edit directly.\n'
const includePattern = /^([\t ]*)\/\/ @include ([a-zA-Z0-9._/-]+)[\t ]*$/gm

function normalized(value) {
  return String(value).replace(/\r\n?/g, '\n').replace(/\s+$/, '') + '\n'
}

async function expand(source, seen) {
  const matches = [...source.matchAll(includePattern)]
  let output = source
  for (const match of matches.reverse()) {
    const relative = match[2]
    const target = path.resolve(sourceRoot, relative)
    if (path.relative(sourceRoot, target).startsWith('..' + path.sep) || target === sourceRoot) throw new Error(`客户端源码 include 越界: ${relative}`)
    if (seen.has(target)) throw new Error(`客户端源码重复 include: ${relative}`)
    seen.add(target)
    const fragment = await expand(normalized(await readFile(target, 'utf8')), seen)
    const indented = fragment.trimEnd().split('\n').map(line => line ? match[1] + line : '').join('\n')
    output = output.slice(0, match.index) + indented + output.slice(match.index + match[0].length)
  }
  return output
}

export async function assembleTavernClient() {
  const template = normalized(await readFile(templatePath, 'utf8'))
  // The bundle installs its stylesheet from this placeholder: substitute the text of
  // the shipped stylesheet so one artifact carries both code and styles.
  const css = await readFile(path.join(root, 'lib/client-assets/tavern.css'), 'utf8')
  const expanded = await expand(template, new Set())
  return banner + normalized(expanded.replace('__TAVERN_BUNDLED_CSS__', () => JSON.stringify(css)))
}

export async function buildTavernClient({ check = false } = {}) {
  const output = await assembleTavernClient()
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current === output) return Object.freeze({ changed: false, path: outputPath })
  if (check) throw new Error('tavern-plugin/lib/client.js 已过期，请运行 pnpm build:client')
  const temporary = outputPath + `.tmp-${process.pid}`
  try {
    await writeFile(temporary, output)
    await rename(temporary, outputPath)
  } finally {
    await unlink(temporary).catch(() => {})
  }
  return Object.freeze({ changed: true, path: outputPath })
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await buildTavernClient({ check: process.argv.includes('--check') })
    console.log(result.changed ? '已生成 tavern-plugin/lib/client.js' : 'tavern-plugin/lib/client.js 已是最新')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
